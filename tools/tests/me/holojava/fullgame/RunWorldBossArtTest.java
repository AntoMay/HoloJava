package me.holojava.fullgame;

import java.io.File;
import java.io.FileInputStream;

/**
 * Pins the boss art mapping decided by the unpacked-art audit: every BOSSES
 * id resolves to a local directory holding exactly the configured frame
 * count, each a real PNG. Independent of the loader arrays, so a typo in
 * either side fails loudly.
 *
 * <p>Decided mapping (audit 2026-10-16): Smol Ame, Nodoka, Goriela,
 * Spiderchama (EldrichHaachama), Area 15 (Moontato), Nanora (Moonafic2
 * fallback), Halloween Bae (Bae3D), Halloween Myth (NurseCalli) replaced
 * wrong/missing art; the rest were already correct.
 *
 * <p>WoWo (Arena Hutan Sawit) is original art generated by
 * tools/generate_palm_forest_sprites.py, not an extracted asset.
 */
public final class RunWorldBossArtTest {

    private static int checks = 0;
    private static int failures = 0;

    /** {bossId, dir, prefix, count} — mirrors the audit, not the loader. */
    private static final String[][] SPEC = {
        {"fubuzilla", "fubuzilla", "spr_fubuzilla_", "12"},
        {"smol_ame", "SmolAme", "spr_SmollAme_walk_", "8"},
        {"mikodanye", "Mikodanye", "spr_Mikodanye_", "8"},
        {"achan", "AchanBoss", "spr_AchanBoss_", "4"},
        {"shubangelion", "Shubangelion_walk", "spr_Shubangelion_walk_", "8"},
        {"spiderchama", "EldrichHaachama", "spr_EldrichHaachama_walk_", "8"},
        {"udin", "Udin_walk", "spr_Udin_walk_", "6"},
        {"area15", "Moontato", "spr_Moontato_", "4"},
        {"nanora", "Nanora", "spr_Moonafic2_", "3"},
        {"pekodam", "Pekodam", "spr_Pekodam_", "4"},
        {"halloween_bae", "BaeBoss", "spr_Bae3D_walk_", "8"},
        {"nodoka", "NodokaBoss", "spr_NodokaBoss_", "4"},
        {"halloween_myth", "NurseCalli", "spr_NurseCalli_", "6"},
        {"goriela", "Goriela", "spr_Goriela_idle_", "4"},
        {"wowo", "WoWo", "spr_WoWo_", "4"},
    };

    public static void main(String[] args) throws Exception {
        expectEq(ContentCatalog.BOSSES.length, SPEC.length, "spec covers every boss");
        for (int i = 0; i < SPEC.length; i++) {
            String id = SPEC[i][0];
            expect(ContentCatalog.boss(id) != null, id + " is defined in the catalog");
            int count = Integer.parseInt(SPEC[i][3]);
            for (int f = 0; f < count; f++) {
                File png = new File("assets/fullgame/bosses/" + SPEC[i][1]
                    + "/" + SPEC[i][2] + f + ".png");
                expect(png.isFile(), id + " frame " + f + " exists (" + png.getPath() + ")");
                if (png.isFile()) expect(isPng(png), id + " frame " + f + " has PNG magic");
            }
        }

        System.out.println("checks=" + checks + " failures=" + failures);
        if (failures > 0) {
            System.out.println("RESULT: FAIL");
            System.exit(1);
        }
        System.out.println("RESULT: PASS");
    }

    private static boolean isPng(File png) {
        try {
            FileInputStream in = new FileInputStream(png);
            byte[] magic = new byte[8];
            int n = 0;
            while (n < 8) {
                int r = in.read(magic, n, 8 - n);
                if (r < 0) break;
                n += r;
            }
            in.close();
            return n == 8 && (magic[0] & 0xFF) == 0x89 && magic[1] == 0x50
                && magic[2] == 0x4E && magic[3] == 0x47;
        } catch (Exception e) {
            return false;
        }
    }

    // ---------------------------------------------------------------- helpers

    private static void expectEq(int got, int want, String label) {
        expect(got == want, label + ": expected " + want + " got " + got);
    }

    private static void expect(boolean ok, String label) {
        checks++;
        if (!ok) {
            failures++;
            System.out.println("  FAIL: " + label);
        }
    }
}
